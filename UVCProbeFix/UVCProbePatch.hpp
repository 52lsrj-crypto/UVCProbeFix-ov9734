// Overflow-safe half-open range check used by the runtime page-geometry gate.
// Avoid `offset + length <= total`, which can wrap size_t on malformed input.
static inline bool rangeFits(size_t offset, size_t length, size_t total) {
    return offset <= total && length <= total - offset;
}

