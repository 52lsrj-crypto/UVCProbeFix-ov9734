enum class HandshakeRegionVariant : uint8_t {
    None = 0,
    Tahoe25G83,
    Tahoe25G229G241
};

static inline HandshakeRegionVariant matchKnownHandshakeRegion(
    const uint8_t *region,
    size_t regionSize) {
    if (region == nullptr || regionSize != kHandshakeRegionSize) {
        return HandshakeRegionVariant::None;
    }
    if (memcmp(region,
               kOriginalHandshakeRegion25G83,
               kHandshakeRegionSize) == 0) {
        return HandshakeRegionVariant::Tahoe25G83;
    }
    if (memcmp(region,
               kOriginalHandshakeRegion25G229G241,
               kHandshakeRegionSize) == 0) {
        return HandshakeRegionVariant::Tahoe25G229G241;
    }
    return HandshakeRegionVariant::None;
}

static inline const uint8_t *originalHandshakeRegionForVariant(
    HandshakeRegionVariant variant) {
    switch (variant) {
        case HandshakeRegionVariant::Tahoe25G83:
            return kOriginalHandshakeRegion25G83;
        case HandshakeRegionVariant::Tahoe25G229G241:
            return kOriginalHandshakeRegion25G229G241;
        default:
            return nullptr;
    }
}

static inline const uint8_t *postGetReplacementForVariant(
    HandshakeRegionVariant variant) {
    switch (variant) {
        case HandshakeRegionVariant::Tahoe25G83:
            return kPostGetReplacement25G83;
        case HandshakeRegionVariant::Tahoe25G229G241:
            return kPostGetReplacement25G229G241;
        default:
            return nullptr;
    }
}

static inline const char *handshakeRegionVariantName(
    HandshakeRegionVariant variant) {
    switch (variant) {
        case HandshakeRegionVariant::Tahoe25G83:
            return "25G83";
        case HandshakeRegionVariant::Tahoe25G229G241:
            return "25G229/25G241";
        default:
            return "unknown";
    }
}

struct ProbeFields {
    uint8_t formatIndex;
    uint8_t frameIndex;
    uint32_t frameInterval;
    uint32_t maxVideoFrameSize;
    uint32_t maxPayloadTransferSize;
};

// 0.2.15 policy: Stage 1 is intentionally disabled. A normal host
// SET_CUR(PROBE) with dwMaxPayloadTransferSize == 0 is passed through exactly
// as observed on the known-good ASUS. For the captured 25G229/25G241 family,
// the exact malformed Frame-4 response is remapped to equivalent Frame 1 at
// 640x480 with payload zero before one real second PROBE round. 25G83 keeps its
// frozen 0.2.12 614400/3072 binary replacement for compatibility.
static inline bool shouldPrepareProbeRequest(const ProbeFields &) {
    return false;
}

static inline bool prepareProbeRequest(ProbeFields &) {
    return false;
}

static inline bool shouldSanitizeProbeResponse(const ProbeFields &probe) {
    return probe.formatIndex == kFormatIndex &&
           probe.frameIndex == kFrameIndex &&
           probe.frameInterval == kFrameInterval100ns &&
           probe.maxVideoFrameSize == kBrokenMaxVideoFrameSize &&
           probe.maxPayloadTransferSize == kBrokenMaxPayloadTransferSize;
}

static inline bool shouldRetryProbeOnce(const ProbeFields &probe,
                                        bool retryAlreadyIssued) {
    return !retryAlreadyIssued && shouldSanitizeProbeResponse(probe);
}

static inline bool sanitizeProbeResponse(ProbeFields &probe) {
    if (!shouldSanitizeProbeResponse(probe)) {
        return false;
    }
    probe.frameIndex = kFallbackFrameIndex;
    probe.maxVideoFrameSize = kExpectedMaxVideoFrameSize;
    probe.maxPayloadTransferSize = 0;
    return true;
}

