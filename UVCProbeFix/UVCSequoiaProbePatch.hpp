// Adaptation of the frozen Tahoe25G229/25G241 Frame4->Frame1 fallback.
// Compare the same two exact qwords, set frameSize=614400/payload=0 and Frame1,
// then toggle byte4 of the saved frameRate qword as the same one-shot flag.
// At this point the saved frameRate at rbp-0x88 is dead (last read at +0x162);
// its high dword starts at rbp-0x84, requiring a 32-bit displacement.
// The normal 333333 frameRate argument supplies an initially zero flag byte.
// R15 has been overwritten by clockFrequency; reload its original request-data
// object from rbp-0x68 before retrying Apple's +0x21A SET_CUR -> GET_CUR path.
// That path reloads R12 (error:) from rbp-0x70 at +0x238. The post-GET status
// remains in R12; non-target probes and second hits keep it unchanged.
// The injected block has no CALL and changes no pre-SET bytes.
static constexpr uint8_t kReplacement[] = {
    0x48, 0xB8, 0x01, 0x04, 0x15, 0x16, 0x05, 0x00, 0x00, 0x00, 0x49, 0x39,
    0x45, 0x02, 0x75, 0x30, 0x48, 0xB8, 0x00, 0x00, 0x00, 0x0B, 0x01, 0x00,
    0x01, 0x01, 0x49, 0x39, 0x45, 0x12, 0x75, 0x20, 0xB8, 0x00, 0x60, 0x09,
    0x00, 0x49, 0x89, 0x45, 0x12, 0x41, 0xC6, 0x45, 0x03, 0x01, 0x80, 0xB5,
    0x7C, 0xFF, 0xFF, 0xFF, 0x01, 0x74, 0x09, 0x4C, 0x8B, 0x7D, 0x98, 0xE9,
    0xD8, 0xFE, 0xFF, 0xFF, 0xEB, 0x40, 0x90,
};

static_assert(sizeof(kOriginalMethod) == kMethodSize, "Sequoia method size changed");
static_assert(sizeof(kReplacement) == kPatchSize, "Sequoia patch size changed");
static_assert(kPostGetOffset + kPatchSize <= kResumeOffset, "Sequoia patch overlaps continuation");
static_assert(0x3BB + kMethodSize <= 4096, "Captured Sequoia method must fit its cache page");

static inline bool isSupportedDarwinVersion(uint32_t major, uint32_t /*minor*/) {
    return major == 24;
}

// Match the entire captured method, including its prologue, local-stack ABI,
// request path and continuation. Reject ambiguous pages and unknown bytes.
static inline bool findUniqueMethod(const uint8_t *page, size_t pageSize,
                                    size_t &methodOffset) {
    if (page == nullptr || pageSize < kMethodSize) return false;
    bool found = false;
    size_t candidate = 0;
    const size_t last = pageSize - kMethodSize;
    for (size_t offset = 0; offset <= last; ++offset) {
        if (memcmp(page + offset, kOriginalMethod, kMethodSize) != 0) continue;
        if (found) return false;
        found = true;
        candidate = offset;
    }
    if (found) methodOffset = candidate;
    return found;
}

static inline bool buildReplacementMethod(uint8_t *replacement, size_t size) {
    if (replacement == nullptr || size != kMethodSize) return false;
    memcpy(replacement, kOriginalMethod, kMethodSize);
    memcpy(replacement + kPostGetOffset, kReplacement, kPatchSize);
    return true;
}

